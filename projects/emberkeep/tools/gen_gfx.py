"""Emberkeep: the original's tile sheet (art/tilesheet.png, from
amiga_mcp/examples/emberkeep/art) -> src/gfx.c.

The original bakes the sheet to 16 x 16 tiles by nearest-neighbour
(tools/bake_tilesheet.py); here the same 16 x 16 samples are mapped to the
Atari's screen (x / 2, y * 3 / 4: 8 x 12) and its colours:

- terrain tiles for ANTIC E (2 bits a pixel): 0 black, 1 grey stone,
  2 brick red, 3 the row's accent (a DLI: the rune's yellow, the oil's
  orange, the portal's green); 2 bytes x 12 lines each
- the player's four poses for players 0 (its red) and 1 (its skin, hair,
  boots: everything else that isn't black), 12 lines each
- the enemies (3 kinds x 8 frames) for one player each, 12 lines

Run: python3 projects/emberkeep/tools/gen_gfx.py (PIL)
"""
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parents[1]
im = Image.open(HERE / "art" / "tilesheet.png").convert("RGB").resize((320, 128), Image.NEAREST)


def cell(row, col):
    return [[im.getpixel((col * 16 + x, row * 16 + y)) for x in range(16)] for y in range(16)]


def scale(c):
    """16 x 16 -> 8 x 12: each Atari pixel the most common non-black of the
    pixels it covers (or black)"""
    out = []
    for L in range(12):
        y0, y1 = (L * 4) // 3, ((L + 1) * 4 + 2) // 3
        row = []
        for X in range(8):
            px = [c[y][x] for y in range(y0, min(y1, 16)) for x in (2 * X, 2 * X + 1)]
            lit = [p for p in px if sum(p) > 90]
            if len(lit) * 2 < len(px):
                row.append((0, 0, 0))
            else:
                row.append(max(set(lit), key=lit.count))
        out.append(row)
    return out


def classify(p, accent):
    """an RGB -> 0 black, 1 grey, 2 red / brown, 3 accent"""
    r, g, b = p
    if r + g + b <= 90:
        return 0
    if accent(p):
        return 3
    if r > g + 40 and r > b + 40:
        return 2
    return 1


def tile_bytes(c, accent=lambda p: False):
    s = scale(c)
    out = []
    for row in s:
        v = 0
        for X in range(8):
            v = v << 2 | classify(row[X], accent)
        out += [v >> 8, v & 255]
    return out


def yellowish(p):
    r, g, b = p
    return r > 150 and g > 120 and b < 120


def greenish(p):
    r, g, b = p
    return g > r + 40 and g > b + 20


def bluish(p):
    r, g, b = p
    return b > r + 40


TILES = [  # (name, sheet row, column, accent test)
    ("FLOOR", 0, 0, None), ("WALL_A", 0, 1, None), ("WALL_B", 0, 2, None),
    ("RUNE", 0, 3, lambda p: yellowish(p) or bluish(p)), ("OIL", 0, 4, yellowish),
    ("HAZARD", 0, 5, None), ("PORTAL_LOCKED", 1, 0, None), ("PORTAL_OPEN", 1, 1, greenish)]

out = ["/* generated by tools/gen_gfx.py from the original's art/tilesheet.png - do not edit */",
       "#include <stdint.h>", ""]
tb = []
for name, r, c, acc in TILES:
    tb += tile_bytes(cell(r, c), acc or (lambda p: False))
out.append("/* terrain: 2 bytes x 12 lines (in LOWDATA: the bank copy reads them) */")
out.append('#pragma rodata-name (push, "LOWDATA")')
out.append(f"const uint8_t tile_gfx[{len(TILES)} * 24] = {{")
for i in range(0, len(tb), 24):
    out.append("    " + ", ".join(f"0x{v:02X}" for v in tb[i:i + 24]) + f",  /* {TILES[i // 24][0]} */")
out.append("};")
out.append("#pragma rodata-name (pop)")


def bits(rows, test):
    return [sum(0x80 >> X for X in range(8) if test(row[X])) for row in rows]


def reddish(p):
    r, g, b = p
    return r > g + 60 and r > b + 60


pl0, pl1 = [], []
for col in range(4):                        # up, right, down, left
    s = scale(cell(4, col))
    pl0 += bits(s, lambda p: sum(p) > 90 and reddish(p))
    pl1 += bits(s, lambda p: sum(p) > 90 and not reddish(p))
en = []
for row in (5, 6, 7):
    for f in range(8):
        en += bits(scale(cell(row, f)), lambda p: sum(p) > 90)


def arr(name, vals):
    out.append(f"const uint8_t {name}[{len(vals)}] = {{")
    for i in range(0, len(vals), 12):
        out.append("    " + ", ".join(f"0x{v:02X}" for v in vals[i:i + 12]) + ",")
    out.append("};")


out.append("/* the player's poses (up, right, down, left): players 0 (red) and 1 */")
arr("pl_gfx0", pl0)
arr("pl_gfx1", pl1)
out.append("/* the enemies: kind (cyan, magenta, grey) x 8 frames x 12 lines */")
arr("en_gfx", en)
(HERE / "src" / "gfx.c").write_text("\n".join(out) + "\n")
for k in range(len(TILES)):
    print(TILES[k][0])
    for L in range(12):
        v = tb[k * 24 + L * 2] << 8 | tb[k * 24 + L * 2 + 1]
        print("".join(".#ox"[(v >> (14 - 2 * X)) & 3] for X in range(8)))
