"""Rotoball: the tables and shapes (src/gfx.c), from the original's
pitch.c (amiga_mcp/examples/rotoball).

The screen is the original's at x / 2, y * 3 / 4: a pane 96 lines (128),
the horizon at line 32 (42), the floor's rows dy = 1..63 below it (a row
dy is the original's row dy * 4 / 3: distance 270 / dy units, dy / 3
pixels a unit, so a two-cell period (10 units) is 10 dy / 3 pixels).

- the floor: row dy's stripes, colour 1 (cell A) and 2 (cell B), a cell
  5 dy / 3 pixels wide, built at run time (floor.c) from row_period here;
  row_tofs[dy] = frac(-24 / dy) (the screen centre's phase, 16 bits),
  row_dcell[dy] = 54 / dy in 8.8 (the row's distance in cells)
- the ball (players 0 and 1, OR'd: the red body and its highlight) for
  the original's radius 3..32: draw_ball_sphere's disc and highlight
- the skimmer (players 2 and 3: the body and its dark outline and skirt)
  for the original's scale 6..40: draw_skimmer's triangles
Each shape: its lines, its player width (1, 2 or 4 colour clocks a bit),
the line of its centre (ball) or ground point (skimmer).

Run: python3 projects/rotoball/tools/gen_gfx.py
"""
from pathlib import Path
import math

HERE = Path(__file__).resolve().parents[1]
ROWS = 63
out = ["/* generated by tools/gen_gfx.py from the original's pitch.c - do not edit */",
       "#include <stdint.h>", '#include "gfx.h"', ""]


def arr(ctype, name, vals, per=16):
    out.append(f"const {ctype} {name}[{len(vals)}] = {{")
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")


# ---- the floor's rows: ANTIC D lines, two scan lines each (lines dy and
# dy + 1 below the horizon, the row's geometry at dy + 0.5): 31 rows, the
# 63rd line the last row again (ANTIC D fetches its bytes once for both
# lines: half the floor's DMA of ANTIC E). The tables floor.s reads are spaced 4 apart (row r at
# 4 r: ra_lo / ra_hi hold its four copies at 4 r + c). A row r: k (its dy), the period in pixels (P8,
# rounded), the screen centre's phase frac(-24 / k) (T8, 1/256), its
# distance 54 / k in cells (D88, 8.8), the bytes its pattern needs (L).
ks = [k + 0.5 for k in range(1, 63, 2)]
P8 = [round(10 * k / 3) for k in ks]
T8 = [round(((-24 / k) % 1) * 256) % 256 for k in ks]
D88 = [round(54 / k * 256) for k in ks]
L = [-(-(p8 + 166) // 4) + 1 for p8 in P8]
out.append(f"/* the floor's {len(ks)} rows (lines 1+2 .. 61+62; 63 is the last again), spaced 4 apart */")


def x4(v):
    r = []
    for a in v:
        r += [a, 0, 0, 0]
    return r[:-3]


arr("uint8_t", "row_p8", x4(P8))
arr("uint8_t", "row_t8", x4(T8))
arr("uint8_t", "row_dlo", x4([d & 255 for d in D88]))
arr("uint8_t", "row_dhi", x4([d >> 8 for d in D88]))
arr("uint8_t", "row_len", L)
arr("uint16_t", "row_w16", [round(5 * k / 3 * 256) for k in ks])   # a cell, 8.8 pixels
print("floor rows", len(ks), "bytes a copy", sum(L))

def mult_for(width_px):
    return 1 if width_px <= 8 else 2 if width_px <= 16 else 4


def to_bits(row_px, mult):
    """a row of pixels (x from -4 * mult .. 4 * mult) -> a player byte"""
    v = 0
    for b in range(8):
        x0 = (b - 4) * mult
        if any(row_px(x0 + i + 0.5) for i in range(mult)):
            v |= 0x80 >> b
    return v


# ---- the ball: radius 3..32 (the original's pixels)
balls, bdata = [], []
for r in range(3, 33):
    rx, ry = r / 2, r * 3 / 4
    mult = mult_for(r)
    h = int(ry)
    hx, hy, hr = -r / 6, -r / 4, r / 6           # highlight: up-left, r / 3
    body, spot = [], []
    for j in range(-h, h + 1):
        def disc(x, j=j):
            return (x / rx) ** 2 + (j / ry) ** 2 <= 1.0

        def hi(x, j=j):
            return r >= 6 and ((x - hx) / max(hr, 0.6)) ** 2 + ((j - hy) / max(hr * 1.5, 0.8)) ** 2 <= 1.0 \
                and disc(x)
        body.append(to_bits(disc, mult))
        spot.append(to_bits(hi, mult))
    balls.append((len(bdata), 2 * h + 1, mult, h))
    bdata += spot + body                        # player 0 (spot), player 1 (body)
out.append("/* the ball, radius 3..32: data offset (player 0 then 1), lines, width, centre */")
arr("uint16_t", "ball_ofs", [b[0] for b in balls])
arr("uint8_t", "ball_h", [b[1] for b in balls])
arr("uint8_t", "ball_w", [b[2] for b in balls])
arr("uint8_t", "ball_c", [b[3] for b in balls])
arr("uint8_t", "ball_data", bdata)

# ---- the skimmer: scale 6..40 (draw_skimmer: a triangle 3 x scale high,
# 2 x scale wide, an outline a pixel round it, a two-line skirt)
skims, sdata = [], []
for s in range(6, 41):
    H = round(3 * s * 3 / 4)                   # apex to ground, lines
    mult = mult_for(s + 1)
    body, edge = [], []
    for j in range(H + 2):                     # line j: apex .. ground .. skirt
        dy = j * 4 / 3                         # the original's rows
        if j <= H:
            hw = (dy + 1) * s / (3 * s) / 2    # half width, Atari pixels
            def b(x, hw=hw): return abs(x) <= hw - 0.25 and j > 0
            def e(x, hw=hw): return abs(x) <= hw + 0.5
            if j == H:                         # the skirt's first line (dark)
                def e(x): return abs(x) <= s / 2 + 0.5
                def b(x): return False
        else:
            def b(x): return False
            def e(x): return abs(x) <= s / 2 - 0.5
        body.append(to_bits(b, mult))
        edge.append(to_bits(e, mult))
    skims.append((len(sdata), H + 2, mult, H))
    sdata += body + edge                       # player 2 (body), player 3 (edge)
out.append("/* the skimmer, scale 6..40: data offset (player 2 then 3), lines, width, ground line */")
arr("uint16_t", "skim_ofs", [x[0] for x in skims])
arr("uint8_t", "skim_h", [x[1] for x in skims])
arr("uint8_t", "skim_w", [x[2] for x in skims])
arr("uint8_t", "skim_g", [x[3] for x in skims])
arr("uint8_t", "skim_data", sdata)

(HERE / "src" / "gfx.c").write_text("\n".join(out) + "\n")
(HERE / "src" / "gfx.h").write_text("""/* tools/gen_gfx.py's tables (src/gfx.c) */
#ifndef GFX_H
#define GFX_H
#include <stdint.h>
#define FROWS 31                /* the floor's rows: ANTIC D, lines 1+2 .. 61+62 */
extern const uint8_t row_p8[], row_t8[], row_dlo[], row_dhi[], row_len[FROWS];
extern const uint16_t row_w16[FROWS];
#define BALL_R0 3
#define BALL_N 30
extern const uint16_t ball_ofs[BALL_N];
extern const uint8_t ball_h[BALL_N], ball_w[BALL_N], ball_c[BALL_N], ball_data[];
#define SKIM_S0 6
#define SKIM_N 35
extern const uint16_t skim_ofs[SKIM_N];
extern const uint8_t skim_h[SKIM_N], skim_w[SKIM_N], skim_g[SKIM_N], skim_data[];
#endif
""")
print("ball bytes", len(bdata), "skimmer bytes", len(sdata))
for row in bdata[balls[20][0]:balls[20][0] + balls[20][1] * 2]:
    print(format(row, "08b").replace("0", ".").replace("1", "#"))
