#!/usr/bin/env python3
"""Writes src/sprites.h: the lander as two players (double width, 8 bits =
16 pixels) seen from behind, for 5 roll angles (-2..2: the drawing turned
by about 9 degrees a step), plus the shadow. Player 0: the descent stage
and the legs (gold); player 1: the ascent stage and the bell (grey); where
they overlap GTIA's multicolour players show a third colour."""
import math
from pathlib import Path

H = 24                       # rows (single-line PMG; drawn every scan line)
# a 16 x 24 picture: 'A' ascent stage, 'D' descent stage, 'L' legs, 'B' the bell, '.' empty
ART = [
    "................",
    "......AAAA......",
    ".....AAAAAA.....",
    "....AAAAAAAA....",
    "....AAAAAAAA....",
    "...AAAAAAAAAA...",
    "...AAAAAAAAAA...",
    "....AAAAAAAA....",
    "...DDDDDDDDDD...",
    "..DDDDDDDDDDDD..",
    "..DDDDDDDDDDDD..",
    "..DDDDDDDDDDDD..",
    "..DDDDDDDDDDDD..",
    "..LDDDDDDDDDDL..",
    ".L..DDDBBDDD..L.",
    ".L.....BB.....L.",
    "L.....BBBB.....L",
    "L.....BBBB.....L",
    "L..............L",
    "L..............L",
    "LL............LL",
    "................",
    "................",
    "................",
]


def rot(roll_step):
    a = math.radians(9 * roll_step)
    c, s = math.cos(a), math.sin(a)
    out = [["."] * 16 for _ in range(H)]
    cx, cy = 7.5, 11.5
    for y in range(H):
        for x in range(16):
            # sample the art at the point that turns onto (x, y)
            dx, dy = x - cx, y - cy
            sx = c * dx - s * dy + cx
            sy = s * dx + c * dy + cy
            ix, iy = round(sx), round(sy)
            if 0 <= ix < 16 and 0 <= iy < H:
                out[y][x] = ART[iy][ix]
    return out


def player_bytes(img, keys):
    rows = []
    for y in range(H):
        v = 0
        for b in range(8):                     # double width: 2 picture pixels a bit
            px = img[y][2 * b] in keys or img[y][2 * b + 1] in keys
            v |= px << (7 - b)
        rows.append(v)
    return rows


frames0, frames1 = [], []
for r in range(-2, 3):
    img = rot(r)
    frames0.append(player_bytes(img, "DL"))
    frames1.append(player_bytes(img, "AB"))
shadow = [0x3C, 0x7E, 0xFF, 0x7E, 0x3C]

lines = ["/* generated by tools/gen_sprites.py */", f"#define SPR_H {H}"]
for name, fr in (("spr_p0", frames0), ("spr_p1", frames1)):
    lines.append(f"static const uint8_t {name}[5][SPR_H] = {{")
    for f in fr:
        lines.append("    { " + ", ".join(f"0x{v:02X}" for v in f) + " },")
    lines.append("};")
lines.append("static const uint8_t spr_shadow[5] = { " + ", ".join(f"0x{v:02X}" for v in shadow) + " };")
out = Path(__file__).resolve().parents[1] / "src" / "sprites.h"
out.write_text("\n".join(lines) + "\n")
print(out)
