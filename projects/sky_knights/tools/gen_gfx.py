"""Sky Knights: the knights and pods as Atari shapes (src/gfx.c), drawn by
the original's draw_rider / draw_egg (amiga_mcp/examples/sky_knights/draw.c)
rectangle for rectangle, then mapped to the screen: a knight's 20 x 20
world pixels are 8 colour clocks (x 2 / 5: a column is the OR of the 2.5
pixels it covers) x 15 lines (y * 3 / 4).

port: the lance and the mount's head point the way the knight flies (the
original draws them on the left for facing 0, which is right; the ZX
Spectrum port does the same).

- kn_mount / kn_rider: players (8 bits a line): frame = facing * 4 +
  flapping * 2 + anim_frame; the mount (body colour) and the rider (knight
  colour, its lance, the beak)
- en_img: the enemies' shape (all of it, one colour) for the bitmap,
  pre-shifted: [frame][x & 3][15 lines][3 bytes] as 2-bit masks (11 a
  pixel); the colour is ANDed in when drawn
- egg_img: a pod, [x & 3][6 lines][2 bytes]

Run: python3 projects/sky_knights/tools/gen_gfx.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
BODY, KNIGHT, WHITE, BEAK = 1, 2, 3, 4


def rider(facing, flapping, anim):
    g = [[0] * 20 for _ in range(24)]          # rows -2..21 -> 0..23 (2 above)

    def r(x0, y0, x1, y1, pen):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if 0 <= x < 20 and -2 <= y < 22:
                    g[y + 2][x] = pen
    left = facing == 1                         # port: face the way it flies
    r(6, 0, 13, 6, KNIGHT)
    r(7, -2, 12, -1, KNIGHT)
    if left:
        r(0, 2, 5, 4, WHITE)
    else:
        r(14, 2, 19, 4, WHITE)
    r(3, 7, 16, 13, BODY)
    r(4, 4, 6, 7, BODY) if left else r(13, 4, 15, 7, BODY)
    if left:
        r(2, 2, 4, 5, BODY)
        r(0, 3, 2, 4, BEAK)
    else:
        r(15, 2, 17, 5, BODY)
        r(17, 3, 19, 4, BEAK)
    if anim == 0:
        r(6, 14, 8, 19, BODY)
        r(12, 14, 14, 17, BODY)
    else:
        r(6, 14, 8, 17, BODY)
        r(12, 14, 14, 19, BODY)
    if flapping:
        r(0, 5, 3, 7, BODY)
        r(16, 5, 19, 7, BODY)
    else:
        r(0, 9, 3, 12, BODY)
        r(16, 9, 19, 12, BODY)
    return g


def to_lines(g, pens, h_world=22, top=0):
    """world rows top.. -> lines (3/4), columns 20 -> 8"""
    lines = []
    nl = (h_world * 3 + 3) // 4
    for L in range(nl):
        r0 = top + (L * 4) // 3
        r1 = max(r0, top + ((L + 1) * 4) // 3 - 1)
        v = 0
        for c in range(8):
            x0, x1 = int(c * 2.5), int((c + 1) * 2.5 - 0.01)
            if any(g[r][x] in pens for r in range(r0, min(r1, len(g) - 1) + 1) for x in range(x0, x1 + 1)):
                v |= 0x80 >> c
        lines.append(v)
    return lines


def shift2bpp(bits8, phase, nbytes):
    """an 8-pixel row at pixel offset phase -> nbytes of 2-bit masks"""
    out = [0] * nbytes
    for p in range(8):
        if bits8 & (0x80 >> p):
            q = p + phase
            out[q // 4] |= 0xC0 >> (2 * (q % 4))
    return out


out = ["/* generated by tools/gen_gfx.py from the original's draw.c - do not edit */",
       "#include <stdint.h>", ""]
H = 16                                         # 22 world rows (head at -2) -> 16 lines
mount, ride, enemy = [], [], []
for facing in (0, 1):
    for flap in (0, 1):
        for anim in (0, 1):
            g = rider(facing, flap, anim)
            mount.append(to_lines(g, {BODY}))
            ride.append(to_lines(g, {KNIGHT, WHITE, BEAK}))
            enemy.append(to_lines(g, {BODY, KNIGHT, WHITE, BEAK}))
nl = len(mount[0])


def arr(name, rows):
    out.append(f"const uint8_t {name}[{len(rows)}][{len(rows[0])}] = {{")
    for r in rows:
        out.append("    {" + ", ".join(f"0x{v:02X}" for v in r) + "},")
    out.append("};")


out.append(f"/* {nl} lines from 2 world pixels above the box (the head) */")
arr("kn_mount", mount)
arr("kn_rider", ride)
imgs = []
for fr in enemy:
    for ph in range(4):
        b = []
        for row in fr:
            b += shift2bpp(row, ph, 3)
        imgs.append(b)
out.append(f"/* [frame * 4 + (x & 3)]: {nl} lines x 3 bytes of 2-bit masks */")
arr("en_img", imgs)
# the pod: 8 x 8 world -> 4 x 6 (draw_egg)
egg = [[0] * 8 for _ in range(8)]
for (x0, y0, x1, y1) in ((1, 0, 6, 1), (0, 2, 7, 5), (1, 6, 6, 7)):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            egg[y][x] = 1
egg_lines = []
for L in range(6):
    r0, r1 = (L * 4) // 3, max((L * 4) // 3, ((L + 1) * 4) // 3 - 1)
    v = 0
    for c in range(4):
        if any(egg[r][x] for r in range(r0, r1 + 1) for x in (2 * c, 2 * c + 1)):
            v |= 0x80 >> c
    egg_lines.append(v)
eimgs = []
for ph in range(4):
    b = []
    for row in egg_lines:
        b += shift2bpp(row, ph, 2)
    eimgs.append(b)
out.append("/* a pod: [x & 3]: 6 lines x 2 bytes */")
arr("egg_img", eimgs)
(HERE / "src" / "gfx.c").write_text("\n".join(out) + "\n")
print("lines", nl)
for v in mount[0]:
    print(format(v, "08b").replace("0", ".").replace("1", "#"), end="  ")
    print()

# ---- src/xfast.inc: the unrolled XOR blits for xspr.s (no clipping)
# The images transposed: table T<k> holds byte k of every image in every
# colour (index colour * n + image), so the code reads byte k as `lda T,x`
# and the whole image is one straight run, 7 rows to a dst base (y < 256).
# Bytes that are 0 in every image are left out.
COLS = (0xAA, 0xFF, 0x55)                     # colour index 0, 1, 2


def fast(name, images, w):
    n, size = len(images), len(images[0])
    h = size // w
    s = [f"; {name}: {n} images x {len(COLS)} colours, {h} lines x {w} bytes",
         "        .rodata"]
    used = []
    for k in range(size):
        vals = [img[k] & c for c in COLS for img in images]
        if any(vals):
            used.append(k)
            s.append(f"{name}_t{k}:")
            for i in range(0, len(vals), 16):
                s.append("        .byte " + ",".join(f"${v:02X}" for v in vals[i:i + 16]))
    s += ["        .code", f"{name}_blit:          ; X = colour * {n} + image, dst = the top left byte"]
    base = 0
    for k in used:
        r, c = divmod(k, w)
        if r - base >= 7:
            step = (r - base) // 7 * 7
            s += ["        clc", "        lda dst", f"        adc #<{step * 40}", "        sta dst",
                  "        lda dst+1", f"        adc #>{step * 40}", "        sta dst+1"]
            base += step
        s += [f"        ldy #{(r - base) * 40 + c}", f"        lda {name}_t{k},x",
              "        eor (dst),y", "        sta (dst),y"]
    s.append("        rts")
    return s, n


inc = ["; generated by tools/gen_gfx.py - do not edit"]
# the enemies: a blit for each x & 3 (the bytes empty in all 8 frames of
# that shift left out: 34-43 of the 51), indexed by colour * 8 + frame
for ph in range(4):
    part, n_en = fast(f"en{ph}", [imgs[f * 4 + ph] for f in range(8)], 3)
    inc += part
part, n_egg = fast("egg", eimgs, 2)
inc += part
inc += [f"EN_N = {n_en}", f"EGG_N = {n_egg}"]
(HERE / "src" / "xfast.inc").write_text("\n".join(inc) + "\n")
