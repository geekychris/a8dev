#!/usr/bin/env python3
"""Writes src/view_tab.h: the board's 13 x 13 grid points on the screen for
3 x 3 tilts (roll and pitch each -max, 0, +max, drawn at twice the tilt as
the original does), from the original's camera (amiga3d: at (0, 470, -430),
pitched 7600/65536 of a turn down, fov 266 on its 320 x 256 view), scaled
to our 160 x 88 mode D lines; and for each tilt and grid row the screen
lines a wall's top (22 units) rises above the floor."""
import math
from pathlib import Path

N, CELL, HALF, WALL_H = 12, 40, 240, 22
TILT = 0.12 * 2                         # the tilt drawn twice as big
CAM = (0, 470, -430)
PITCH = 7600 / 65536 * 2 * math.pi
FOV, CX, CY = 266, 160, 128 + 6
# our screen: x 160 wide, 88 lines of 2 scan lines; mode D pixels are ~1.17x taller than wide
K = 0.88
SX, SY, OX, OY = 0.5 * K, 0.5 / 1.17 * K, 80, 46 - 17


def project(x, y, z, roll, pitch):
    cr, sr, cp, sp = math.cos(roll), math.sin(roll), math.cos(pitch), math.sin(pitch)
    x1, y1 = x * cr + y * sr, y * cr - x * sr
    z2, y2 = z * cp + y1 * sp, y1 * cp - z * sp
    dx, dy, dz = x1 - CAM[0], y2 - CAM[1], z2 - CAM[2]
    c, s = math.cos(PITCH), math.sin(PITCH)
    yc = dy * c + dz * s
    zc = dz * c - dy * s
    sx = CX + dx * FOV / zc
    sy = CY - yc * FOV / zc
    return OX + (sx - CX) * SX, OY + (sy - CY) * SY


views, rise = [], []
for pr in (-1, 0, 1):                   # pitch: the far side down for +
    for rr in (-1, 0, 1):               # roll: the right side down for +
        pts, rs = [], []
        for j in range(N + 1):          # grid row 0 = the far edge (z = +HALF)
            z = HALF - j * CELL
            row_r = []
            for i in range(N + 1):
                x = -HALF + i * CELL
                px, py = project(x, 0, z, rr * TILT, pr * TILT)
                pts.append((round(px), round(py)))
                tx, ty = project(x, WALL_H, z, rr * TILT, pr * TILT)
                row_r.append(py - ty)
            rs.append(round(sum(row_r) / len(row_r)))
        views.append(pts)
        rise.append(rs)
xs = [p[0] for v in views for p in v]
ys = [p[1] for v in views for p in v]
print("x", min(xs), max(xs), "y", min(ys), max(ys), "rise", min(min(r) for r in rise), max(max(r) for r in rise))
assert min(xs) >= 0 and max(xs) <= 160 and min(ys) - max(max(r) for r in rise) >= 0 and max(ys) <= 87

out = Path(__file__).resolve().parents[1] / "src" / "view_tab.h"
lines = ["/* generated by tools/gen_view.py: [view = pitch * 3 + roll][row 0..12][col 0..12] */",
         "static const uint8_t view_x[9][169] = {"]
for v in views:
    lines.append("    { " + ", ".join(str(p[0]) for p in v) + " },")
lines.append("};")
lines.append("static const uint8_t view_y[9][169] = {")
for v in views:
    lines.append("    { " + ", ".join(str(p[1]) for p in v) + " },")
lines.append("};")
lines.append("static const uint8_t view_rise[9][13] = {")
for r in rise:
    lines.append("    { " + ", ".join(str(x) for x in r) + " },")
lines.append("};")
out.write_text("\n".join(lines) + "\n")
print(out)
