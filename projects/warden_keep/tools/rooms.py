"""Warden Keep's rooms and a solver (breadth-first over the player's place,
the barrels' places and the jewels taken), with the original's rules
(game.cpp: walls and barrels block, a barrel is pushed if the tile beyond
is inside and free, a jewel is taken by walking onto it; a barrel can be
pushed onto a jewel and then hides it).

Room 1 is the original's (load_room). Rooms 2-4 are new (port: the
original has one room; its README lists more as follow-up work): the same
pieces, the back walls, the door at 7,7.

    python3 tools/rooms.py          # checks every room is solvable, prints
                                    # the shortest routes (tools/routes.txt)
                                    # and writes src/rooms.c
"""
from collections import deque
from pathlib import Path

ROOMS = [
    ("THE GUARD ROOM", [
        "########",
        "#.......",
        "#.B..B..",
        "#.....J.",
        "#.......",
        "#..B.B..",
        "#.JP..J.",
        "#.......",
    ]),
    ("THE STORE", [
        "########",
        "#J.B....",
        "#..B....",
        "#BB..B..",
        "#.....J.",
        "#.B.B...",
        "#J..P...",
        "#.......",
    ]),
    ("THE CRYPT", [
        "########",
        "#..J....",
        "#.#..#..",
        "#..B..B.",
        "#.B.J...",
        "#.#..#B.",
        "#..P..J.",
        "#.......",
    ]),
    ("THE VAULT", [
        "########",
        "#J..B..J",
        "#.B.B.B.",
        "#..#.#..",
        "#.B...B.",
        "#..#.#..",
        "#B..P..B",
        "#..J....",
    ]),
]

DIRS = {"U": (0, -1), "D": (0, 1), "L": (-1, 0), "R": (1, 0)}


def parse(rows):
    walls, barrels, jewels, start = set(), [], [], None
    for wy, row in enumerate(rows):
        for wx, ch in enumerate(row):
            if ch == "#": walls.add((wx, wy))
            elif ch == "B": barrels.append((wx, wy))
            elif ch == "J": jewels.append((wx, wy))
            elif ch == "P": start = (wx, wy)
    return walls, barrels, jewels, start


def step(walls, state, d, jewels):
    (px, py), barrels, taken = state
    dx, dy = DIRS[d]
    tx, ty = px + dx, py + dy
    bl = list(barrels)
    # object_at: walls first, then barrels, then jewels (load_room's order)
    if (tx, ty) in walls:
        return state
    if (tx, ty) in bl:
        bx, by = tx + dx, ty + dy
        if not (0 <= bx < 8 and 0 <= by < 8): return state
        if (bx, by) in walls or (bx, by) in bl: return state
        bl[bl.index((tx, ty))] = (bx, by)
    if not (0 <= tx < 8 and 0 <= ty < 8): return state
    t = set(taken)
    # pickup: the first object there; a barrel hides the jewel
    if (tx, ty) in jewels and (tx, ty) not in t and (tx, ty) not in bl:
        t.add((tx, ty))
    return ((tx, ty), tuple(sorted(bl)), frozenset(t))


def solve(rows):
    walls, barrels, jewels, start = parse(rows)
    s0 = (start, tuple(sorted(barrels)), frozenset())
    prev = {s0: None}
    q = deque([s0])
    while q:
        s = q.popleft()
        if len(s[2]) == len(jewels):
            path = []
            while prev[s]:
                s, d = prev[s]
                path.append(d)
            return "".join(reversed(path))
        for d in DIRS:
            n = step(walls, s, d, jewels)
            if n != s and n not in prev:
                prev[n] = (s, d)
                q.append(n)
    return None


if __name__ == "__main__":
    out = []
    for name, rows in ROOMS:
        r = solve(rows)
        print(f"{name}: {len(r) if r else 'UNSOLVABLE'} steps {r}")
        out.append(r or "")
    (Path(__file__).parent / "routes.txt").write_text("\n".join(out) + "\n")
    # src/rooms.c: per room its name, the start, then the objects in
    # object_at's order (blocks, barrels, jewels) as kind, wx, wy; 0 ends
    c = ["/* generated by tools/rooms.py - do not edit */", '#include "game.h"', ""]
    for i, (name, rows) in enumerate(ROOMS):
        walls, barrels, jewels, start = parse(rows)
        inner = sorted((x, y) for (x, y) in walls if x and y)
        objs = [(1, x, y) for x, y in inner] + [(2, x, y) for x, y in barrels] + [(3, x, y) for x, y in jewels]
        c.append(f"static const uint8_t room{i}[] = {{{start[0]}, {start[1]}, "
                 + "".join(f"{k}, {x}, {y}, " for k, x, y in objs) + "0};")
    c.append("const uint8_t *const room_data[NUM_ROOMS] = {" + ", ".join(f"room{i}" for i in range(len(ROOMS))) + "};")
    c.append("const char *const room_name[NUM_ROOMS] = {" + ", ".join(f'"{n}"' for n, _ in ROOMS) + "};")
    (Path(__file__).resolve().parents[1] / "src" / "rooms.c").write_text("\n".join(c) + "\n")
