#!/usr/bin/env python3
"""Rock Blaster: the original's outlines -> src/shapes.c.

The world is the original's 320 pixels across; the Atari shows it at
160 colour clocks (2 world pixels a colour clock) and 1 world pixel a scan
line, so every shape keeps the original's proportions on the TV. The rocks
are in an ANTIC D bitmap (rows of 2 scan lines): one pixel = 2 x 2 world
pixels; the ship (players) has the full resolution.

- rocks: each of the 12 outlines (3 sizes x 4 shapes) is drawn in world
  pixels, folded to colour clocks and stored as rows of pixels relative to
  its centre, every pixel once (the game draws them with XOR, so a pixel
  drawn twice would vanish): [rows, first dy], then per row the count and
  the x offsets + 32 (draw.s indexes its tables with them), top to bottom
  (rows of the bitmap).
- ship and flame: the outlines' corners rotated to 64 angles (the ship turns
  in 256 steps; every 4 share a picture), for a 16 colour clocks x 25 lines
  picture (players 0+1 for the ship, 2+3 for the flame; centre at line 12,
  bit 8): the game draws the lines between them when the angle changes.
Run: python3 tools/mkshapes.py
"""
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent

SHIP = [(10, 0), (-7, -6), (-4, -2), (-4, 2), (-7, 6)]
FLAME = [(-5, -3), (-12, 0), (-5, 3)]
ROCKS = [
    [[(-8, -18), (8, -20), (20, -8), (18, 4), (12, 18), (-4, 20), (-18, 10), (-20, -6)],
     [(-12, -16), (4, -20), (18, -12), (20, 2), (10, 18), (-8, 16), (-20, 4), (-16, -10)],
     [(-6, -20), (10, -16), (20, -4), (16, 10), (4, 20), (-10, 16), (-20, 2), (-14, -12)],
     [(-14, -14), (2, -20), (16, -14), (20, 0), (14, 16), (-2, 20), (-18, 8), (-18, -8)]],
    [[(-4, -10), (4, -12), (12, -4), (10, 4), (6, 10), (-2, 12), (-10, 6), (-12, -2)],
     [(-6, -8), (2, -12), (10, -6), (12, 2), (6, 10), (-4, 10), (-12, 2), (-8, -6)],
     [(-2, -12), (6, -10), (12, -2), (8, 6), (2, 12), (-6, 8), (-12, 0), (-8, -8)],
     [(-8, -8), (2, -12), (10, -8), (12, 0), (8, 8), (0, 12), (-10, 4), (-10, -4)]],
    [[(-2, -5), (2, -6), (6, -2), (5, 2), (3, 5), (-1, 6), (-5, 3), (-6, -1)],
     [(-3, -4), (1, -6), (5, -3), (6, 1), (3, 5), (-2, 5), (-6, 1), (-4, -3)],
     [(-1, -6), (3, -5), (6, -1), (4, 3), (1, 6), (-3, 4), (-6, 0), (-4, -4)],
     [(-4, -4), (1, -6), (5, -4), (6, 0), (4, 4), (0, 6), (-5, 2), (-5, -2)]],
]


def line(x0, y0, x1, y1):
    """Bresenham, both ends included (graphics.library's Draw)."""
    pts = []
    dx, dy = abs(x1 - x0), -abs(y1 - y0)
    sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
    err = dx + dy
    while True:
        pts.append((x0, y0))
        if x0 == x1 and y0 == y1:
            return pts
        e2 = 2 * err
        if e2 >= dy:
            err += dy
            x0 += sx
        if e2 <= dx:
            err += dx
            y0 += sy


def outline(poly):
    pts = set()
    for i in range(len(poly)):
        (x0, y0), (x1, y1) = poly[i], poly[(i + 1) % len(poly)]
        pts.update(line(x0, y0, x1, y1))
    return pts


def fold(pts):
    """world pixels -> ANTIC D pixels (x // 2 colour clocks, y // 2 rows of
    2 scan lines), each pixel once"""
    return {(x // 2, y // 2) for x, y in pts}


def rotate(poly, a):
    s, c = math.sin(a * 2 * math.pi / 256), math.cos(a * 2 * math.pi / 256)
    # the original's rotate(): (px*c - py*s) >> 16 with 16.16 trig (floor)
    S, C = round(s * 65536), round(c * 65536)
    return [((px * C - py * S) >> 16, (px * S + py * C) >> 16) for px, py in poly]


out = ["/* generated by tools/mkshapes.py - do not edit */", "#include <stdint.h>", '#include "shapes.h"', ""]
# rocks: per shape: n_rows, dy of the first row, then per row: count, dx...
rock_ptrs = []
blob = []
for size in range(3):
    for k in range(4):
        px = fold(outline(ROCKS[size][k]))
        ys = sorted({y for _, y in px})
        rows = [sorted(x for x, yy in px if yy == y) for y in range(ys[0], ys[-1] + 1)]
        rock_ptrs.append(len(blob))
        blob += [len(rows), ys[0] & 0xFF]
        for r in rows:
            blob += [len(r)] + [x + 32 for x in r]
out.append(f"const uint8_t rock_data[{len(blob)}] = {{")
for i in range(0, len(blob), 20):
    out.append("    " + ", ".join(str(v) for v in blob[i:i + 20]) + ",")
out.append("};")
out.append("const uint16_t rock_shape_off[12] = { " + ", ".join(map(str, rock_ptrs)) + " };")
# time to move one (erase + draw), in units of 2 scan lines (VCOUNT): the
# inner loop is ~41 cycles a pixel, ~45 a row, and ANTIC takes ~25% of the
# cycles while the bitmap shows
def cost(size, k):
    px = fold(outline(ROCKS[size][k]))
    rows = len({y for _, y in px})
    return math.ceil((len(px) * 2 * 41 + rows * 2 * 45) * 1.3 / 228) + 1


out.append("const uint8_t rock_cost[12] = { " + ", ".join(str(cost(s_, k)) for s_ in range(3) for k in range(4)) + " };")
out.append("const uint8_t rock_pixels[12] = { " + ", ".join(
    str(len(fold(outline(ROCKS[s][k])))) for s in range(3) for k in range(4)) + " };")

# ship + flame: the outlines' corners rotated to 64 angles, in colour
# clocks + 8 and lines + 12 (render.c draws the lines into the players)
def verts(poly, name):
    # the players have single-line resolution: 1 world pixel a scan line
    out.append(f"const uint8_t {name}[64 * {len(poly)} * 2] = {{")
    for f in range(64):
        pts = []
        for x, y in rotate(poly, f * 4):
            col, row = x // 2 + 8, y + 12
            assert 0 <= col < 16 and 0 <= row < SH_H, (name, f, x, y)
            pts += [col, row]
        out.append("    " + ", ".join(map(str, pts)) + ",")
    out.append("};")


SH_H = 25
verts(SHIP, "ship_verts")
verts(FLAME, "flame_verts")
(HERE / "src" / "shapes.c").write_text("\n".join(out) + "\n")
(HERE / "src" / "shapes.h").write_text("""/* generated by tools/mkshapes.py - do not edit */
#ifndef SHAPES_H
#define SHAPES_H
#include <stdint.h>
#define SHIP_H 25               /* lines of a ship/flame frame (centre: line 12) */
/* rock outlines: [rows, first dy, then per row: count, dx + 32...] (colour clocks) */
extern const uint8_t rock_data[];
extern const uint16_t rock_shape_off[12];   /* size * 4 + shape */
extern const uint8_t rock_pixels[12];
extern const uint8_t rock_cost[12];       /* VCOUNT units to move one */
/* 64 angles x corners x (column 0..15, line 0..24) */
#define SHIP_VERTS 5
#define FLAME_VERTS 3
extern const uint8_t ship_verts[64 * SHIP_VERTS * 2];
extern const uint8_t flame_verts[64 * FLAME_VERTS * 2];
#endif
""")
print(len(blob), "bytes of rock outlines;", [len(fold(outline(ROCKS[s][k]))) for s in range(3) for k in range(4)])
