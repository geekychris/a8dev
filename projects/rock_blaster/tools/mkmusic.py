#!/usr/bin/env python3
"""Rock Blaster: the original's MOD (tools/rock_blaster.mod, "rock storm")
-> src/music.c, two POKEY channels for music_play().

The MOD's lead and bass channels (the two the Spectrum port's AY plays) are
read row by row in song order; each note lasts until the next note on its
channel. Amiga periods are turned into MIDI notes (period 428 = C-2 in
ProTracker = MIDI 60 here); both fit the SDK's notes (MIDI 48 up).
Speed = ticks a row (50 Hz).
Run: python3 tools/mkmusic.py [--show]
"""
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
d = (HERE / "tools" / "rock_blaster.mod").read_bytes()
songlen = d[950]
order = list(d[952:952 + songlen])
npat = max(d[952:952 + 128]) + 1


def cell(p, row, ch):
    o = 1084 + p * 1024 + row * 16 + ch * 4
    b = d[o:o + 4]
    inst = (b[0] & 0xF0) | (b[2] >> 4)
    period = ((b[0] & 0x0F) << 8) | b[1]
    eff, arg = b[2] & 0x0F, b[3]
    return inst, period, eff, arg


def midi(period):
    return round(60 + 12 * math.log2(428 / period))


speed = 6
rows = []                        # (ticks, [note or None per channel])
for p in order:
    for r in range(64):
        cells = [cell(p, r, c) for c in range(4)]
        for inst, per, eff, arg in cells:
            if eff == 0xF and 0 < arg < 32:
                speed = arg
        rows.append((speed, [midi(per) if per else None for _, per, _, _ in cells],
                     [inst for inst, *_ in cells]))

if "--show" in sys.argv:
    for ch in range(4):
        notes = [n[ch] for _, n, _ in rows if n[ch] is not None]
        insts = sorted({i[ch] for _, _, i in rows if i[ch]})
        print(ch, len(notes), "notes", min(notes, default=0), max(notes, default=0), "instruments", insts)
    sys.exit()

# the lead (channel 0, instrument 1) and the bass (channel 1, instrument 2):
# the two the Spectrum port plays. Channel 2 is drums (one pitch, three
# samples), channel 3 a counter-melody; --show lists them.
lead, bass = 0, 1


def track(ch, shift):
    out = []
    cur, length = 0, 0
    for ticks, n, _ in rows:
        if n[ch] is not None:
            if length:
                out.append((cur, length))
            cur, length = n[ch] + shift, 0
        length += ticks
    out.append((cur, length))
    if out[0][0] == 0 and out[0][1] == 0:
        out = out[1:]
    res = []
    for note, ln in out:                   # a8_note.len is a byte
        while ln > 255:
            res.append((note, 255))
            ln -= 255
        res.append((note, ln))
    for note, _ in res:
        assert note == 0 or 48 <= note <= 107, note
    return res


lt, bt = track(lead, 0), track(bass, 0)
assert sum(l for _, l in lt) == sum(l for _, l in bt)
lines = ["/* generated by tools/mkmusic.py from tools/rock_blaster.mod - do not edit */",
         '#include "a8game.h"', '#include "music.h"', ""]
for name, t in (("music_lead", lt), ("music_bass", bt)):
    lines.append(f"const a8_note {name}[{len(t) + 1}] = {{")
    for i in range(0, len(t), 10):
        lines.append("    " + ", ".join(f"{{{n},{l}}}" for n, l in t[i:i + 10]) + ",")
    lines.append("    {0, 0}\n};")
(HERE / "src" / "music.c").write_text("\n".join(lines) + "\n")
(HERE / "src" / "music.h").write_text(
    "/* generated by tools/mkmusic.py - do not edit */\n#ifndef MUSIC_H\n#define MUSIC_H\n#include \"a8game.h\"\n"
    f"extern const a8_note music_lead[{len(lt) + 1}], music_bass[{len(bt) + 1}];\n#endif\n")
print(f"lead ch{lead}: {len(lt)} notes, bass ch{bass}: {len(bt)} notes, {sum(l for _, l in lt)} frames")
