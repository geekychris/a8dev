def player_shape(c, pens, x0=0, w=16):
    """columns x0..x0+15 of canvas c -> a player: 8 bits a line, a bit when
    either of its two world pixels has one of `pens`; world rows -> lines
    (y * 3 / 4, a line ORs the rows it covers)"""
    h = c.h * 3 // 4
    rows = []
    for L in range(h):
        r0 = (L * 4) // 3
        r1 = max(r0, ((L + 1) * 4) // 3 - 1)
        v = 0
        for b in range(8):
            on = any(c.p[r][x] in pens for r in range(r0, min(r1, c.h - 1) + 1)
                     for x in (x0 + 2 * b, x0 + 2 * b + 1) if x < c.w)
            if on:
                v |= 0x80 >> b
        rows.append(v)
    return rows


