"""Orb Hunter: generates src/data.c from the original.

- the world: the original's levels.c rooms (8 x 6 rooms of 20 x 16 tiles,
  made on the host by the ZX Spectrum port's tools/gen_world.c from the
  original's own levels.c: spectrum_dev/projects/orb_hunter/gfx/world.bin),
  run-length coded a room at a time (a byte: count << 4 | tile)
- the items (levels.c place_items)
- the tiles as ANTIC E pictures: 8 colour clocks x 12 lines (a tile is
  16 x 16 world pixels: x / 2, y * 3 / 4), 2 bytes a line, from the
  original's draw_tile designs (draw.c)
- the sprites as player shapes (8 colour clocks wide, the original's
  sprite rows mapped to lines): its draw_hunter / draw_enemy_* routines,
  rectangle for rectangle (as the Spectrum port's tools/gen_gfx.py draws
  them)

Run from the repo root: python3 projects/orb_hunter/tools/gen_data.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
SPEC = Path.home() / "code/claude_world/spectrum_dev/projects/orb_hunter"

(BG, WHITE, HUNTER, HUNTER2, ROCK, ROCK2, METAL, METAL2, LAVA, LAVA2, MISSILE, ENEMY, ENEMY2, DOOR, ITEM,
 BEAM) = range(16)

world = (SPEC / "gfx" / "world.bin").read_bytes()
assert len(world) == 48 * 320

out = ["/* generated by tools/gen_data.py from the original - do not edit */",
       "#include <stdint.h>", ""]


def arr(name, typ, vals, per=16):
    out.append(f"const {typ} {name}[{len(vals)}] = {{")
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")


# ---- the world, a room after another (room (x, y) is room y * 8 + x)
rle, offs = [], []
for r in range(48):
    tiles = world[r * 320:(r + 1) * 320]
    offs.append(len(rle))
    i = 0
    while i < 320:
        t, n = tiles[i], 1
        while i + n < 320 and tiles[i + n] == t and n < 15:
            n += 1
        rle.append((n << 4) | t)
        i += n
out.append("/* the rooms, run-length coded (count << 4 | tile), and where each starts */")
arr("world_rle", "uint8_t", rle, 20)
arr("world_off", "uint16_t", offs, 12)
print(f"world: {len(world)} bytes -> {len(rle)} run-length coded")


# ---- tiles: 16 x 16 world pens -> 8 x 12 Atari pixels (values 0..3)
def lines_of(rows16):
    """16 world rows -> 12 lines: line L takes the rows floor(L*4/3)..; a
    pixel is the brightest (highest value) of what it covers"""
    out_rows = []
    for L in range(12):
        r0, r1 = (L * 4) // 3, max((L * 4) // 3, ((L + 1) * 4) // 3 - 1)
        row = []
        for c in range(8):
            v = 0
            for r in range(r0, r1 + 1):
                for x in (2 * c, 2 * c + 1):
                    v = max(v, rows16[r][x])
            row.append(v)
        out_rows.append(row)
    return out_rows


def grid(fill=0):
    return [[fill] * 16 for _ in range(16)]


def rect(g, x0, y0, x1, y1, v):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if 0 <= x < 16 and 0 <= y < 16:
                g[y][x] = v


# colour values in the room: 1 = the area's rock, 2 = its highlight, 3 = the
# row's special colour (lava / door / metal / item, set by a DLI a row)
def t_rock():
    g = grid(1)
    for x, y in ((3, 2), (10, 5), (6, 11), (13, 9), (1, 7), (8, 14), (14, 2), (5, 6)):
        rect(g, x, y, x + 1, y, 2)          # its specks (doubled: a pixel is 2 wide)
    return g


def t_brick():
    g = grid(1)
    for y in (3, 7, 11, 15):
        rect(g, 0, y, 15, y, 2)
    for x, y0 in ((7, 0), (15, 4), (7, 8), (15, 12)):
        rect(g, x - 1, y0, x, y0 + 3, 2)
    return g


def t_metal():
    g = grid(3)
    rect(g, 0, 0, 15, 0, 2)
    rect(g, 0, 0, 1, 15, 2)
    rect(g, 14, 0, 15, 15, 0)
    rect(g, 0, 15, 15, 15, 0)
    return g


def t_platform():
    g = grid(0)
    rect(g, 0, 0, 15, 2, 1)
    rect(g, 0, 3, 15, 3, 2)
    return g


def t_lava(frame):
    g = grid(0)
    rect(g, 0, 2, 15, 15, 3)
    wave = (frame // 4) & 3
    for x in range(16):
        wy = 0 if ((x + wave) & 3) > 1 else 1
        rect(g, x, wy, x, wy + 1, 2)
    for dx, y in ((3, 6), (9, 10), (5, 13)):
        x = (frame + dx) & 15
        rect(g, x, y, x + 1, y, 2)
    return g


def t_door():
    g = grid(0)
    for x0 in (2, 7, 12):
        rect(g, x0, 0, x0 + 2, 15, 3)
    rect(g, 2, 3, 14, 4, 3)
    rect(g, 2, 11, 14, 12, 3)
    return g


def t_item():
    g = grid(3)
    rect(g, 0, 0, 15, 0, 2)
    rect(g, 0, 15, 15, 15, 2)
    rect(g, 0, 0, 0, 15, 2)
    rect(g, 15, 0, 15, 15, 2)
    rect(g, 6, 6, 9, 9, 2)
    return g


S_GLYPH = [0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E]     # the 5 x 7 font's S


def t_save():
    g = grid(0)
    rect(g, 4, 2, 11, 13, 3)
    for r, bits in enumerate(S_GLYPH):
        for c in range(5):
            if bits & (0x10 >> c):
                rect(g, 5 + c, 4 + r, 5 + c, 4 + r, 0)
    return g


def pack(rows12):
    b = []
    for row in rows12:
        for half in (row[:4], row[4:]):
            v = 0
            for p in half:
                v = (v << 2) | p
            b.append(v)
    return b


TILES = [grid(0), t_rock(), t_brick(), t_metal(), t_platform(), t_lava(0), t_door(), grid(0), t_item(), t_save()]
tile_bytes = []
for t in TILES:
    tile_bytes += pack(lines_of(t))
out.append("/* the 10 tiles (TILE_*), 12 lines x 2 bytes; lava's 4 frames after them */")
lava = []
for f in (0, 4, 8, 12):
    lava += pack(lines_of(t_lava(f)))
