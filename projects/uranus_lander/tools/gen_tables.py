"""Uranus Lander: generates src/tables.c from the Amiga original.

- thrust_x/thrust_y: the original's thrust for each angle,
  (sin_tab[a] * 3200) >> 16 and (-cos_tab[a] * 3200) >> 16, from its own
  16.16 table (sin_precomp in amiga_mcp/examples/uranus_lander/game.c), so
  the physics is the Amiga's to the bit.
- the lander and its flame in 32 directions as player shapes: the
  original's polygons (draw.c: lander_x/y, flame_x/y, flame_big_y) rotated
  by its rotate() and drawn at the Atari's pixel size (a colour clock = 2
  world pixels, a line = 4/3). Centre: column 4, line 7 (ship) / line 7
  (flame).

Run from the repo root: python3 projects/uranus_lander/tools/gen_tables.py
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
AMIGA = Path.home() / "code/claude_world/amiga_mcp/examples/uranus_lander"
src = (AMIGA / "game.c").read_text()
body = src[src.index("sin_precomp[256] = {"):]
body = body[body.index("{") + 1:body.index("};")]
SIN = [int(v) for v in re.findall(r"-?\d+", body)]
assert len(SIN) == 256
COS = [SIN[(i + 64) & 255] for i in range(256)]
THRUST = 3200

LANDER_X = [0, 4, 4, 7, 3, -3, -7, -4, -4]
LANDER_Y = [-7, -3, 1, 6, 3, 3, 6, 1, -3]
FLAME_X = [-2, 0, 2]
FLAME_Y = [3, 9, 3]
FLAME_BIG_Y = [3, 12, 3]
DIRS = 32
H = 16                      # lines a shape
CX, CY = 4, 7               # the centre in the shape (column, line)


def rotate(px, py, a):
    s, c = SIN[a & 255], COS[a & 255]
    return (px * c - py * s) >> 16, (px * s + py * c) >> 16   # the original's (floor)


def shape(xs, ys, a, close=True, extra=()):
    rows = [0] * H
    pts = [rotate(x, y, a) for x, y in zip(xs, ys)]
    edges = list(zip(pts, pts[1:] + (pts[:1] if close else [])))

    def plot(wx, wy):
        col = int((wx + 2 * CX) // 2)          # world x / 2, centre at column 4
        line = int(round(wy * 3 / 4)) + CY
        if 0 <= col < 8 and 0 <= line < H:
            rows[line] |= 0x80 >> col
    for (x0, y0), (x1, y1) in edges:
        n = max(abs(x1 - x0), abs(y1 - y0)) * 2 + 1
        for i in range(n + 1):
            plot(x0 + (x1 - x0) * i / n, y0 + (y1 - y0) * i / n)
    for x, y in extra:
        plot(*rotate(x, y, a))
    return rows


out = ["/* generated by tools/gen_tables.py from the Amiga original - do not edit */",
       "#include <stdint.h>", ""]
out.append("/* (sin_tab[a] * 3200) >> 16, (-cos_tab[a] * 3200) >> 16: the original's thrust */")
for name, tab in (("thrust_x", [(SIN[a] * THRUST) >> 16 for a in range(256)]),
                  ("thrust_y", [(-COS[a] * THRUST) >> 16 for a in range(256)])):
    out.append(f"const int16_t {name}[256] = {{")
    for i in range(0, 256, 16):
        out.append("    " + ", ".join(str(v) for v in tab[i:i + 16]) + ",")
    out.append("};")
for name, xs, ys, close, extra in (("ship_shape", LANDER_X, LANDER_Y, True, [(0, -8)]),
                                   ("flame_shape", FLAME_X, FLAME_Y, True, []),
                                   ("flame_big_shape", FLAME_X, FLAME_BIG_Y, True, [])):
    out.append(f"/* {DIRS} directions x {H} lines; direction d = angle {256 // DIRS} * d */")
    out.append(f"const uint8_t {name}[{DIRS}][{H}] = {{")
    for d in range(DIRS):
        rows = shape(xs, ys, d * (256 // DIRS), close, extra)
        out.append("    {" + ", ".join(f"0x{r:02X}" for r in rows) + "},")
    out.append("};")
# the original's stars (generate_stars: seed 777777, its LCG): x, y
seed = 777777
xs, ys = [], []
for i in range(60):
    seed = (seed * 1103515245 + 12345) & 0xFFFFFFFF
    xs.append((seed >> 16) % 320)
    ys.append((seed >> 3) % (256 - 30))
out.append("/* the original's 60 stars (generate_stars, seed 777777): x, y */")
out.append("const int16_t star_x0[60] = {" + ", ".join(map(str, xs)) + "};")
out.append("const uint8_t star_y0[60] = {" + ", ".join(map(str, ys)) + "};")
# the LCG's constant, 1103515245, a byte at a time times 0..255 (rng.s)
C = 1103515245
out.append("/* (1103515245 >> 8j & 255) * x for x 0..255, low and high bytes (rng.s) */")
for j in range(4):
    cj = (C >> (8 * j)) & 255
    prods = [cj * x for x in range(256)]
    out.append(f"const uint8_t mc{j}_lo[256] = {{" + ", ".join(str(p & 255) for p in prods) + "};")
    if j < 3:
        out.append(f"const uint8_t mc{j}_hi[256] = {{" + ", ".join(str(p >> 8) for p in prods) + "};")
(HERE / "src" / "tables.c").write_text("\n".join(out) + "\n")
print("wrote src/tables.c")
for r in shape(LANDER_X, LANDER_Y, 0, True, [(0, -8)]):
    print(format(r, "08b").replace("0", ".").replace("1", "#"))
