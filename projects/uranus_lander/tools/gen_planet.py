"""Uranus Lander: the title's planet (src/planet.c) from the Amiga original.

The original blits an 80 x 72, 16-colour picture of Uranus (planet_gfx.h,
4 bitplanes; its palette is main.c's). Here it becomes 54 lines of ANTIC E
(40 colour clocks wide, 4 colours) with its own three colours on every
line, set by a DLI per line: each line's colours are the three Atari
colours (the emulator's palette) its pixels use most, black is the
background.

Run from the repo root: .venv/bin/python projects/uranus_lander/tools/gen_planet.py
"""
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
ROOT = HERE.parents[1]
AMIGA = Path.home() / "code/claude_world/amiga_mcp/examples/uranus_lander"
sys.path.insert(0, str(ROOT / "tools" / "a8dev" / "src"))
from a8dev.emu import Emulator  # noqa: E402

W, H, DEPTH, ROWB = 80, 72, 4, 10
src = (AMIGA / "planet_gfx.h").read_text()
planes = []
for p in range(DEPTH):
    body = src[src.index(f"planet_plane{p}[720] = {{"):]
    body = body[body.index("{") + 1:body.index("};")]
    planes.append([int(v, 16) for v in re.findall(r"0x[0-9A-Fa-f]+", body)])
main = (AMIGA / "main.c").read_text()
pal = main[main.index("palette[16] = {"):]
pal = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{3}),", pal[:pal.index("};")])]
AMIGA_RGB = [(((c >> 8) & 15) * 17, ((c >> 4) & 15) * 17, (c & 15) * 17) for c in pal]


def amiga_pixel(x, y):
    i = 0
    for p in range(DEPTH):
        if planes[p][y * ROWB + x // 8] & (0x80 >> (x & 7)):
            i |= 1 << p
    return AMIGA_RGB[i] if i else None        # 0 = deep space: the background


with Emulator() as emu:
    raw = emu.palette()
ATARI = [tuple(raw[i * 3:i * 3 + 3]) for i in range(256)]


def nearest(rgb, choices):
    return min(choices, key=lambda c: sum((a - b) ** 2 for a, b in zip(ATARI[c], rgb)))


LINES = H * 3 // 4                             # 54
COLS = W // 2                                  # 40 colour clocks
pixels, palettes = [], []
for line in range(LINES):
    y = min(H - 1, round(line * 4 / 3))
    row = []
    for x in range(COLS):
        a, b = amiga_pixel(2 * x, y), amiga_pixel(2 * x + 1, y)
        px = [c for c in (a, b) if c]
        if len(px) == 0 or (len(px) == 1 and (a is None) != (b is None) and x % 2):
            row.append(None)
        else:
            row.append(tuple(sum(c[k] for c in px) // len(px) for k in range(3)))
    atari = [nearest(c, range(256)) if c else None for c in row]
    top = [c for c, _ in Counter(c for c in atari if c is not None).most_common(3)]
    while len(top) < 3:
        top.append(0)
    palettes.append(top)
    pixels.append([0 if c is None else 1 + top.index(nearest(ATARI[c], top)) for c in atari])

out = ["/* generated by tools/gen_planet.py from the Amiga original's planet - do not edit */",
       "#include <stdint.h>", "",
       f"/* {LINES} lines of ANTIC E, 10 bytes (40 pixels) each */",
       f"const uint8_t planet_bits[{LINES * 10}] = {{"]
for row in pixels:
    b = []
    for i in range(0, COLS, 4):
        v = 0
        for p in row[i:i + 4]:
            v = (v << 2) | p
        b.append(f"0x{v:02X}")
    out.append("    " + ", ".join(b) + ",")
out.append("};")
out.append(f"/* each line's PF0, PF1, PF2 (Atari colours) */")
out.append(f"const uint8_t planet_pal[{LINES}][3] = {{")
for t in palettes:
    out.append("    {" + ", ".join(f"0x{c:02X}" for c in t) + "},")
out.append("};")
(HERE / "src" / "planet.c").write_text("\n".join(out) + "\n")
print("wrote src/planet.c")
for row in pixels[::2]:
    print("".join(" .:#"[p] for p in row))
