#!/usr/bin/env python3
"""Writes src/tower_geom.h: the tower's column segments for each of the 16
view positions a column (the original's camera: 640 from the axis, core
radius 140, focal length 196 on our 160-pixel line, the vertical
perspective left out). A column j (relative to the one facing you) is shown
when its centre is less than 56/256 of a turn round; its edges are clamped
to the silhouette (44 pixels each side of x = 56); the limbs are dimmer."""
import math
from pathlib import Path

R, D, F, CX, HALF, STEPS = 140, 640, 196, 56, 44, 16


def edge_x(t):
    a = 2 * math.pi * t / 256
    x = int(R * math.sin(a) * F / (D - R * math.cos(a)))
    return CX + max(-HALF, min(HALF, x))


n, rel, xa, xb, dim = [], [], [], [], []
for s in range(STEPS):
    r, a, b, d = [], [], [], []
    for j in range(-5, 6):
        tc = 16 * j - s
        if -56 <= tc <= 56:
            r.append(j)
            a.append(edge_x(tc - 8))
            b.append(edge_x(tc + 8))
            d.append(0xCC if abs(tc) > 36 else 0xFF)
    n.append(len(r))
    pad = 10 - len(r)
    rel.append(r + [0] * pad); xa.append(a + [0] * pad); xb.append(b + [0] * pad); dim.append(d + [0] * pad)


def tab(name, typ, rows):
    body = ",\n".join("    { " + ", ".join(str(v) for v in row) + " }" for row in rows)
    return f"static const {typ} {name}[{STEPS}][10] = {{\n{body}\n}};\n"


out = Path(__file__).resolve().parents[1] / "src" / "tower_geom.h"
out.write_text("/* generated by tools/gen_tower.py */\n"
               f"static const uint8_t seg_n[{STEPS}] = {{ {', '.join(map(str, n))} }};\n"
               + tab("seg_rel", "int8_t", rel) + tab("seg_a", "uint8_t", xa)
               + tab("seg_b", "uint8_t", xb) + tab("seg_d", "uint8_t", dim))
print(out)
