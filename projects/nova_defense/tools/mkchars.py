#!/usr/bin/env python3
"""Nova Defense: the original's sprite art -> src/chars.c.

The swarm is an ANTIC 4 character block (4 colour clocks x 8 lines a
character, 2 bits a pixel): an alien is 7 colour clocks (the original's 14
pixels, two by two) x 10 lines, in 3 characters x 2 rows. Columns are 13
colour clocks apart, so an alien starts at any of the 4 pixels of a
character: every alien is stored at the 4 phases. The original animates
odd columns a frame out of step with even ones, and a column's phase has
its parity, so charset A holds frame (phase & 1) and charset B the other:
swapping CHBASE animates the whole swarm.

'#' body = COLPF0, 'o' accent = COLPF1 (set per alien row by a display-list
interrupt), explosion = COLPF2. Codes: 1.. aliens (type * 4 + phase) * 6 +
k (k 0-2 top row, 3-5 bottom), then explosions (phase * 6 + k), then the
comet (2 characters x 1 row). Also the ship (player 3, 8 colour clocks)
and the shields' rows of bits come from here.
Run: python3 tools/mkchars.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent

ART_C = [["....######....", "..##########..", ".####oooo####.", "####oo..oo####", ".####oooo####.",
          "..##########..", "...#..##..#...", "..#...##...#..", ".#....##....#.", "..#........#.."],
         ["....######....", "..##########..", ".####oooo####.", "####o..oo#####", ".####oooo####.",
          "..##########..", "...#..##..#...", "....#.##.#....", "...#..##..#...", "....#....#...."]]
ART_B = [["#............#", "##....##....##", "###..####..###", "##############", ".####o##o####.",
          "..##########..", "....##..##....", "...##....##...", "..............", ".............."],
         ["..............", "..............", "......##......", "#....####....#", "##############",
          ".####o##o####.", "..##########..", "....##..##....", "....#....#....", ".............."]]
ART_A = [["......##......", ".....####.....", "....##oo##....", "...########...", "..##.####.##..",
          ".##..####..##.", "##...#..#...##", "....##..##....", "...##....##...", ".............."],
         ["......##......", ".....####.....", "....##oo##....", "...########...", "..##.####.##..",
          "..##.####.##..", "..#..#..#..#..", "...#.#..#.#...", "....#....#....", ".............."]]
PLAYER = [".......#.......", "......###......", "......#o#......", "..#..#####..#..",
          "..#.#######.#..", ".#############.", "###############", "##.##.....##.##"]
UFO = ["........oo......", "......oooooo....", "####ooooooooo...", "..##############",
       "####ooooooooo...", "......oooooo....", "........oo......"]
BOOM = ["...x...", "x..x..x", ".x.x.x.", "..xxx..", "xxxxxxx", "..xxx..", ".x.x.x.", "x..x..x",
        "...x...", "......."]


def halve(art):
    """two original pixels -> one colour clock; the accent wins"""
    out = []
    for row in art:
        row = row + "." * (len(row) % 2)
        r = ""
        for i in range(0, len(row), 2):
            pair = row[i:i + 2]
            r += "o" if "o" in pair else ("#" if "#" in pair else ".")
        out.append(r)
    return out


VAL = {".": 0, "#": 1, "o": 2, "x": 3}


def cells(art, phase, wchars=3):
    """art (colour clocks) at x = phase in wchars characters x 2 rows:
    6 x 8 bytes: top row chars, then bottom row"""
    out = []
    for crow in range(2):
        for ch in range(wchars):
            b = []
            for line in range(8):
                y = crow * 8 + line
                v = 0
                for px in range(4):
                    x = ch * 4 + px - phase
                    c = art[y][x] if 0 <= y < len(art) and 0 <= x < len(art[y]) else "."
                    v |= VAL[c] << (6 - 2 * px)
                b.append(v)
            out.append(bytes(b))
    return out


arts = [ART_C, ART_B, ART_A]
charsets = []
for which in range(2):
    cs = [bytes(8)]                       # code 0: blank
    for t in range(3):
        for p in range(4):
            frame = (p & 1) ^ which
            cs += cells(halve(arts[t][frame]), p)
    for p in range(4):
        cs += cells(BOOM, p)
    ufo = halve(UFO)
    cs += cells(ufo, 0, 2)[:2]           # the comet's single row (7 lines)
    assert len(cs) <= 128, len(cs)
    charsets.append(b"".join(cs) + bytes(8 * (128 - len(cs))))
n_codes = 1 + 72 + 24 + 2


def bits(art, width):
    rows = []
    for r in art:
        v = 0
        for x in range(width):
            if x < len(r) and r[x] != ".":
                v |= 0x80 >> x
        rows.append(v)
    return rows


ship = bits(halve(PLAYER), 8)
lines = ["/* generated by tools/mkchars.py - do not edit */", "#include <stdint.h>", '#include "chars.h"', ""]
for i, cs in enumerate(charsets):
    lines.append(f"const uint8_t charset_{'ab'[i]}[1024] = {{")
    for k in range(0, 1024, 16):
        lines.append("    " + ", ".join(f"0x{v:02X}" for v in cs[k:k + 16]) + ",")
    lines.append("};")
lines.append("const uint8_t ship_shape[8] = { " + ", ".join(f"0x{v:02X}" for v in ship) + " };")
(HERE / "src" / "chars.c").write_text("\n".join(lines) + "\n")
(HERE / "src" / "chars.h").write_text(f"""/* generated by tools/mkchars.py - do not edit */
#ifndef CHARS_H
#define CHARS_H
#include <stdint.h>
#define CH_ALIEN(type, phase) (1 + ((type) * 4 + (phase)) * 6)   /* + 0..2 top, 3..5 bottom */
#define CH_BOOM(phase)        (73 + (phase) * 6)
#define CH_COMET              97                                  /* 2 characters */
extern const uint8_t charset_a[1024], charset_b[1024];
extern const uint8_t ship_shape[8];
#endif
""")
print(n_codes, "codes")
