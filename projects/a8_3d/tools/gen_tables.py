#!/usr/bin/env python3
"""Writes lib/a3d_sin.inc: Q7 sine, 256 steps a turn, 320 entries (cos = +64)."""
import math
from pathlib import Path

vals = [max(-127, min(127, round(127 * math.sin(2 * math.pi * i / 256)))) for i in range(320)]
out = Path(__file__).resolve().parents[1] / "lib" / "a3d_sin.inc"
lines = [", ".join(str(v) for v in vals[i:i + 16]) + "," for i in range(0, 320, 16)]
out.write_text("/* generated by tools/gen_tables.py */\n" + "\n".join(lines) + "\n")
