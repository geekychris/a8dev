"""Frank the Frog: ANTIC 4 tile art -> src/tiles.c.

Each object is drawn as 4*n x 16 pixel art (. = background, a = COLPF0,
b = COLPF1, c = COLPF2), cut into 4x8 characters, de-duplicated and numbered
from 64 (codes 0..63 keep the ROM font: letters for the ANTIC 2 rows).
Output: tile_font[] (the characters' bytes) and, per object, its top and
bottom row of character codes. Run: python3 tools/mkfont.py
"""
