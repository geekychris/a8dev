def log(w):
    rows = []
    for y in range(16):
        r = []
        for x in range(w):
            if y < 2 or y > 13:
                r.append(".")
            elif y == 2:
                r.append("b" if 2 <= x < w - 2 else ".")
            elif x < 2 or x >= w - 2:
                r.append("c" if 4 <= y <= 11 and (x == 1 or x == w - 2) else
                         ("a" if 3 <= y <= 12 and (x == 0 or x == w - 1) and 5 <= y <= 10 else
                          ("a" if 3 <= y <= 12 and x in (1, w - 2) else ".")))
            elif y == 13:
                r.append("c")
            elif (x * 7 + y * 3) % 11 == 0 and 4 <= y <= 11:
                r.append("c")
            elif y in (6, 10) and (x // 3) % 2 == 0:
                r.append("b")
            else:
                r.append("a")
        rows.append("".join(r))
    return rows


def art(s):
    rows = [r.replace(" ", "") for r in s.strip("\n").split("\n")]
    assert len(rows) == 16, (len(rows), s)
    return rows


OBJECTS = {
    "car_r": art(CAR), "car_l": flip(art(CAR)),
    "bus_r": art(BUS), "bus_l": flip(art(BUS)),
    "log24": log(24), "log32": log(32),
    "pads": [a + b for a, b in zip(art(PAD), art(PAD_FLOWER))],
    "frog": art(FROG), "water": art(WATER), "grass": art(GRASS),
}

chars, codes = [], {}
out_objs = {}
for name, rows in OBJECTS.items():
    w = len(rows[0])
    assert all(len(r) == w for r in rows) and w % 4 == 0, name
    tops, bots = [], []
    for half, dst in ((0, tops), (8, bots)):
        for cx in range(0, w, 4):
            b = bytes(sum(V[rows[half + y][cx + i]] << (6 - 2 * i) for i in range(4)) for y in range(8))
            if b == bytes(8):
                dst.append(0)                   # blank: screen code 0 (space)
                continue
            if b not in codes:
                codes[b] = 64 + len(chars)
                chars.append(b)
            dst.append(codes[b])
    out_objs[name] = (tops, bots)
assert len(chars) <= 64, len(chars)

lines = ["/* generated by tools/mkfont.py: ANTIC 4 tiles (codes 64..) */",
         "#include <stdint.h>", '#include "tiles.h"', "",
         f"const uint8_t tile_font[{len(chars) * 8}] = {{"]
for c in chars:
    lines.append("    " + ", ".join(f"0x{v:02X}" for v in c) + ",")
lines.append("};")
hdr = ["/* generated by tools/mkfont.py */", "#ifndef TILES_H", "#define TILES_H", "#include <stdint.h>",
       f"#define TILE_COUNT {len(chars)}", "extern const uint8_t tile_font[TILE_COUNT * 8];"]
for name, (t, b) in out_objs.items():
    lines.append(f"const uint8_t t_{name}[{len(t) * 2}] = {{ {', '.join(map(str, t + b))} }};")
    hdr.append(f"#define T_{name.upper()}_W {len(t)}")
    hdr.append(f"extern const uint8_t t_{name}[{len(t) * 2}];   /* top row, then bottom row */")
hdr.append("#endif")
(HERE / "src" / "tiles.c").write_text("\n".join(lines) + "\n")
(HERE / "src" / "tiles.h").write_text("\n".join(hdr) + "\n")
print(f"{len(chars)} characters")
